import 'package:flutter/material.dart';

import 'design_tokens.dart';
import 'style_family.dart';

/// Registry of token packs — add new styles here without rewriting components.
typedef TokenPackBuilder = DesignTokens Function({
  required bool dark,
  required SpacingDensity spacing,
  required ContrastLevel contrast,
  required bool reducedMotion,
});

class TokenPackRegistry {
  TokenPackRegistry._();

  static final Map<VisualStyleFamily, TokenPackBuilder> _packs = {
    VisualStyleFamily.signature: signaturePack,
    VisualStyleFamily.naturalistic: naturalisticPack,
    VisualStyleFamily.softCute: softCutePack,
    VisualStyleFamily.neoBrutal: neoBrutalPack,
    VisualStyleFamily.aurora: auroraPack,
    VisualStyleFamily.quietFocus: quietFocusPack,
  };

  static DesignTokens resolve({
    required VisualStyleFamily family,
    required bool dark,
    required SpacingDensity spacing,
    required ContrastLevel contrast,
    required bool reducedMotion,
  }) {
    final builder = _packs[family] ?? signaturePack;
    return builder(
      dark: dark,
      spacing: spacing,
      contrast: contrast,
      reducedMotion: reducedMotion,
    );
  }

  static void register(VisualStyleFamily family, TokenPackBuilder builder) {
    _packs[family] = builder;
  }

  static Iterable<VisualStyleFamily> get registered => _packs.keys;
}

DesignTokens _base({
  required String styleId,
  required bool dark,
  required SpacingDensity spacing,
  required ContrastLevel contrast,
  required bool reducedMotion,
  required Color bg,
  required Color bgElevated,
  required Color bgMuted,
  required Color surface,
  required Color surfaceElevated,
  required Color textPrimary,
  required Color textSecondary,
  required Color textMuted,
  required Color border,
  required Color divider,
  required Color primaryAction,
  required Color onPrimaryAction,
  required Color secondaryAccent,
  required Color onSecondaryAccent,
  required Color positive,
  required Color warning,
  required Color urgent,
  required Color destructive,
  required Color focusRing,
  required Color shadowColor,
  required Color decorationAccent,
  required Color pressureCalm,
  required Color pressureWatch,
  required Color pressureTight,
  required Color pressureMissing,
  double radiusSm = 8,
  double radiusMd = 14,
  double radiusLg = 20,
  double radiusXl = 28,
  double cardElevation = 0,
}) {
  var tp = textPrimary;
  var tm = textMuted;
  var ts = textSecondary;
  var b = border;
  if (contrast == ContrastLevel.increased) {
    tp = dark ? const Color(0xFFF8FBF9) : const Color(0xFF0A100E);
    tm = dark ? const Color(0xFFC5D0CA) : const Color(0xFF3A4540);
    ts = dark ? const Color(0xFFE2EAE6) : const Color(0xFF1C2622);
    b = dark ? const Color(0xFFA8B8B0) : const Color(0xFF2A3832);
  }

  return DesignTokens(
    bg: bg,
    bgElevated: bgElevated,
    bgMuted: bgMuted,
    surface: surface,
    surfaceElevated: surfaceElevated,
    textPrimary: tp,
    textSecondary: ts,
    textMuted: tm,
    border: b,
    divider: divider,
    primaryAction: primaryAction,
    onPrimaryAction: onPrimaryAction,
    secondaryAccent: secondaryAccent,
    onSecondaryAccent: onSecondaryAccent,
    positive: positive,
    warning: warning,
    urgent: urgent,
    destructive: destructive,
    focusRing: focusRing,
    shadowColor: shadowColor,
    decorationAccent: decorationAccent,
    pressureCalm: pressureCalm,
    pressureWatch: pressureWatch,
    pressureTight: pressureTight,
    pressureMissing: pressureMissing,
    radiusSm: radiusSm,
    radiusMd: radiusMd,
    radiusLg: radiusLg,
    radiusXl: radiusXl,
    spaceUnit: spacing.spaceUnit,
    cardElevation: cardElevation,
    motionScale: reducedMotion ? 0.0 : 1.0,
    editorialDisplay: 'Manrope',
    bodyFamily: 'Manrope',
    styleId: styleId,
  );
}

